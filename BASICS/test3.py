# The round() function takes a float value and returns the nearest integer.
print(round(3.14))
print(round(7.7))
print(round(-2.2))
print(round(-2.6))

# Also accepts an optional second argument specifying to how many decimal places it should round
print(round(3.1415, 1))
print(round(3.1415, 2))
print(round(3.1415, 3))
print(round(7.7777, 3))
print(round(7.7777))


# abs() returns the absolute value of the number argument/the distance from 0/positive form of the number

print(abs(25))
print(abs(-25))
print(abs(3.14))
print(abs(-3.14))
print(abs(0))
print(abs(-0))
print(abs(1))
print(abs(-1))
